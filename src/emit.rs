use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// One classmap entry: FQCN → absolute path.
pub type ClassMap = BTreeMap<String, PathBuf>;

/// Emit `vendor/composer/autoload_classmap.php` content.
///
/// Composer sorts the map by `ksort` (byte-wise ASCII), uses `array(...)`
/// syntax, single-quoted strings, and prefixes paths with either
/// `$baseDir . '/...'` (project) or `$vendorDir . '/...'` (vendor packages).
pub fn render_classmap_php(map: &ClassMap, root: &Path, vendor_dir: &Path) -> String {
    let mut s = String::with_capacity(map.len() * 96);
    s.push_str("<?php\n\n// autoload_classmap.php @generated by Composer\n\n");
    s.push_str("$vendorDir = dirname(__DIR__);\n");
    s.push_str("$baseDir = dirname($vendorDir);\n\n");
    s.push_str("return array(\n");

    for (fqcn, path) in map {
        let escaped_fqcn = escape_php_single_quote(fqcn);
        let path_expr = render_path_expr(path, root, vendor_dir, PathStyle::Var);
        s.push_str("    '");
        s.push_str(&escaped_fqcn);
        s.push_str("' => ");
        s.push_str(&path_expr);
        s.push_str(",\n");
    }

    s.push_str(");\n");
    s
}

/// Render the inner body of `autoload_static.php`'s `$classMap = array(...)`
/// section — i.e. just the entry lines, indented as Composer indents them
/// (8 spaces). Caller wraps in the surrounding scaffold.
pub fn render_static_classmap_body(map: &ClassMap, root: &Path, vendor_dir: &Path) -> String {
    let mut s = String::with_capacity(map.len() * 96);
    for (fqcn, path) in map {
        let escaped_fqcn = escape_php_single_quote(fqcn);
        let path_expr = render_path_expr(path, root, vendor_dir, PathStyle::DirRelative);
        s.push_str("        '");
        s.push_str(&escaped_fqcn);
        s.push_str("' => ");
        s.push_str(&path_expr);
        s.push_str(",\n");
    }
    s
}

/// Replace the `$classMap = array (...);` section of an existing
/// `autoload_static.php` with a freshly-rendered body. We only touch the
/// classMap section — everything else (file hashes, PSR-4 prefix maps, the
/// class-name suffix that pairs this file with autoload_real.php, the
/// `getInitializer` block) is preserved byte-for-byte. That's deliberate:
/// our tool's job is to update the classmap, and Composer owns the rest.
pub fn replace_static_classmap(
    existing: &str,
    new_body: &str,
) -> Result<String> {
    // Locate the start of `public static $classMap = array (`.
    let needle = "public static $classMap = array (";
    let start = existing
        .find(needle)
        .context("autoload_static.php has no $classMap section to replace")?;
    // Find the line break after the opening.
    let after_open = start
        + existing[start..]
            .find('\n')
            .context("malformed $classMap opening line")?
        + 1;
    // Find the closing `    );` line — it's a literal `);` at column 4 (4 leading spaces).
    // Search from after_open forward for the first occurrence of "\n    );".
    let close_marker = "\n    );";
    let close_rel = existing[after_open..]
        .find(close_marker)
        .context("autoload_static.php $classMap section has no closing `    );`")?;
    let close = after_open + close_rel + 1; // points at the start of `    );`

    let mut out = String::with_capacity(existing.len() - (close - after_open) + new_body.len());
    out.push_str(&existing[..after_open]);
    out.push_str(new_body);
    out.push_str(&existing[close..]);
    Ok(out)
}

#[derive(Copy, Clone)]
enum PathStyle {
    /// `$vendorDir . '/foo'` / `$baseDir . '/foo'` — used in autoload_classmap.php.
    Var,
    /// `__DIR__ . '/..' . '/foo'` (vendor) or `__DIR__ . '/../..' . '/foo'` (root) —
    /// used inline inside vendor/composer/autoload_static.php.
    DirRelative,
}

fn render_path_expr(path: &Path, root: &Path, vendor_dir: &Path, style: PathStyle) -> String {
    if let Ok(rel) = path.strip_prefix(vendor_dir) {
        let rel = rel.to_string_lossy();
        match style {
            PathStyle::Var => format!("$vendorDir . '/{}'", rel),
            PathStyle::DirRelative => format!("__DIR__ . '/..' . '/{}'", rel),
        }
    } else if let Ok(rel) = path.strip_prefix(root) {
        let rel = rel.to_string_lossy();
        match style {
            PathStyle::Var => format!("$baseDir . '/{}'", rel),
            PathStyle::DirRelative => format!("__DIR__ . '/../..' . '/{}'", rel),
        }
    } else {
        // File outside both root and vendor — use absolute. Composer would
        // emit an absolute literal here too; this is rare (custom classmap
        // pointing outside the project).
        format!("'{}'", escape_php_single_quote(&path.to_string_lossy()))
    }
}

fn escape_php_single_quote(s: &str) -> String {
    // PHP single-quoted strings only need `\` and `'` escaped.
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            _ => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_simple_classmap() {
        let mut map = ClassMap::new();
        map.insert(
            "Foo\\Bar".to_string(),
            PathBuf::from("/proj/app/Foo/Bar.php"),
        );
        let s = render_classmap_php(
            &map,
            Path::new("/proj"),
            Path::new("/proj/vendor"),
        );
        assert!(s.contains("'Foo\\\\Bar' => $baseDir . '/app/Foo/Bar.php',"));
        assert!(s.starts_with("<?php\n\n// autoload_classmap.php @generated by Composer\n\n"));
        assert!(s.ends_with(");\n"));
    }

    #[test]
    fn renders_vendor_path() {
        let mut map = ClassMap::new();
        map.insert(
            "Vendor\\Cls".to_string(),
            PathBuf::from("/proj/vendor/acme/lib/src/Cls.php"),
        );
        let s = render_classmap_php(
            &map,
            Path::new("/proj"),
            Path::new("/proj/vendor"),
        );
        assert!(s.contains("$vendorDir . '/acme/lib/src/Cls.php'"));
    }

    #[test]
    fn replaces_static_classmap() {
        let existing = "<?php\n\
            namespace Composer\\Autoload;\n\
            class Foo {\n\
            \x20\x20\x20\x20public static $files = array(\n\
            \x20\x20\x20\x20\x20\x20\x20\x20'a' => 'b',\n\
            \x20\x20\x20\x20);\n\n\
            \x20\x20\x20\x20public static $classMap = array (\n\
            \x20\x20\x20\x20\x20\x20\x20\x20'Old\\\\Class' => 'old.php',\n\
            \x20\x20\x20\x20);\n\n\
            \x20\x20\x20\x20public static function getInitializer() {}\n\
            }\n";
        let new_body = "        'New\\\\Class' => 'new.php',\n";
        let out = replace_static_classmap(existing, new_body).unwrap();
        assert!(out.contains("'New\\\\Class' => 'new.php',"));
        assert!(!out.contains("'Old\\\\Class'"));
        assert!(out.contains("public static $files"));
        assert!(out.contains("getInitializer"));
    }

    #[test]
    fn escapes_backslash_and_quote() {
        assert_eq!(escape_php_single_quote("Foo\\Bar"), "Foo\\\\Bar");
        assert_eq!(escape_php_single_quote("it's"), "it\\'s");
    }
}
